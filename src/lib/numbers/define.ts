/** How the number definitions of a family are written: see `@/lib/identity/countries`. */
import { pad2 } from './checksums'
import { rejectionSampler } from './helpers'
import { dateParts, randomPersonSeed } from './person'
import type { NumberSource, NumberType, PersonSeed } from './types'

export const pad3 = (value: number) => String(value).padStart(3, '0')
export const isMale = (person: PersonSeed) => person.sex === 'male'
/** yymmdd, with an offset added to the month where a number encodes the century or sex there. */
export const yymmdd = (person: PersonSeed, monthOffset = 0) => {
  const { yy, month, day } = dateParts(person.birthDate)
  return pad2(yy) + pad2(month + monthOffset) + pad2(day)
}
export const ddmmyy = (person: PersonSeed) => {
  const { yy, month, day } = dateParts(person.birthDate)
  return pad2(day) + pad2(month) + pad2(yy)
}

export interface TypeDefinition extends Omit<NumberType, 'badge' | 'generate' | 'source'> {
  badge?: string
  /** The python-stdnum module the algorithm is ported from. */
  stdnum?: string
  document?: NumberSource['document']
  /** A number for `person`, or '' when the draw has no valid check digit. */
  candidate: (person: PersonSeed) => string
}

/** A kind of number generated by drawing candidates for a person until one is valid. */
export function defineType({
  candidate,
  stdnum,
  document,
  ...definition
}: TypeDefinition): NumberType {
  const generate = rejectionSampler(candidate, definition.isValid)
  return {
    ...definition,
    badge: definition.badge ?? definition.name,
    source: { stdnum, document },
    generate: person => generate(person ?? randomPersonSeed()),
  }
}
